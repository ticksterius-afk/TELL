/**
 * Generates model/fixtures/tell/synthetic-arkit.json: a seeded synthetic TELL
 * session (ARKit-style blendshapes, numbers only) so the scorer's golden test
 * and the Swift port have something to replay before real fixtures exist.
 * Real sessions recorded with the Mien developer recorder replace this as the
 * tuning set in M4; this file only pins today's behaviour.
 *
 *   npm run fixture:tell && npm run golden:tell
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { arkitFace, rng } from "../tests/helpers.ts";
import { FIXTURE_DIR, type TellFixture } from "./make-golden-tell.ts";

const FPS = 25;
const rnd = rng(2026);
const r4 = (v: number) => Math.round(v * 1e3) / 1e3;

const frames: TellFixture["frames"] = [];
let t = 0;
function emit(seconds: number, face: (sec: number) => Record<string, number> | null, cmd?: string): void {
  const n = Math.round(seconds * FPS);
  for (let i = 0; i < n; i++) {
    const sec = i / FPS;
    const m = face(sec);
    const noisy = m ? Object.fromEntries(Object.entries(m).map(([k, v]) => [k, r4(k.startsWith("pose.") ? v + (rnd() - 0.5) * 0.6 : Math.max(0, Math.min(1, v + (rnd() + rnd() - 1) * 0.03)))])) : null;
    const f: TellFixture["frames"][number] = { t: Math.round(t), m: noisy };
    if (i === 0 && cmd) f.cmd = cmd;
    frames.push(f);
    t += 1000 / FPS;
  }
}
function mark(cmd: string): void {
  frames.push({ t: Math.round(t), m: arkitFace({}), cmd });
  t += 1000 / FPS;
}

/** Talking: the jaw and lips move; a 120 ms blink every `blinkEvery` seconds. */
const talking = (blinkEvery: number, extra: (sec: number) => Record<string, number> = () => ({})) => (sec: number): Record<string, number> =>
  arkitFace({
    jawOpen: 0.12 * Math.abs(Math.sin(sec * 5)),
    mouthFunnel: 0.08 * Math.abs(Math.sin(sec * 3 + 1)),
    "mouthStretch{S}": 0.06 * Math.abs(Math.sin(sec * 4 + 2)),
    ...(blinkEvery > 0 && sec % blinkEvery < 0.12 ? { "eyeBlink{S}": 0.9 } : {}),
    ...extra(sec),
  });

emit(1.5, () => arkitFace({}), "calibrate:1");
emit(12, talking(3), "baseline");
emit(8, talking(3), "statement:1");
// Statement 2: eyes held open, a smile leaking through between 4 s and 7 s, slightly one-sided.
emit(9, talking(0, (sec): Record<string, number> => (sec >= 4 && sec < 7 ? { mouthSmileLeft: 0.4, mouthSmileRight: 0.25, "cheekSquint{S}": 0.2 } : {})), "statement:2");
// Statement 3: brows rise for two seconds.
emit(8, talking(3, (sec): Record<string, number> => (sec >= 2 && sec < 4 ? { browInnerUp: 0.45, "browOuterUp{S}": 0.4 } : {})), "statement:3");
mark("end");
mark("false:2");
// A 30 s Poker Face feed: resting face, a smile at 10–14 s, a brow raise at 22 s, 0.6 s of lost face at 18 s.
emit(30, (sec) =>
  sec >= 18 && sec < 18.6
    ? null
    : arkitFace({
      ...(sec % 4 < 0.12 ? { "eyeBlink{S}": 0.9 } : {}),
      ...(sec >= 10 && sec < 14 ? { "mouthSmile{S}": 0.6, "cheekSquint{S}": 0.4 } : {}),
      ...(sec >= 22 && sec < 23 ? { browInnerUp: 0.4, "browOuterUp{S}": 0.4 } : {}),
    }), "feed");
mark("end");

const fixture: TellFixture = {
  name: "synthetic-arkit",
  platform: "arkit",
  about: "Synthetic TELL session generated by web/scripts/make-tell-fixture.ts (seeded noise, ARKit-style blendshapes, no camera). Baseline, three statements (the second holds the eyes open and leaks a one-sided smile; the third raises the brows), then a 30 s Poker Face feed.",
  frames,
};
mkdirSync(FIXTURE_DIR, { recursive: true });
writeFileSync(new URL("synthetic-arkit.json", FIXTURE_DIR), JSON.stringify(fixture) + "\n");
console.log(`wrote model/fixtures/tell/synthetic-arkit.json (${frames.length} frames, ${(t / 1000).toFixed(1)} s)`);
